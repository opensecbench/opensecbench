//go:build ignore

// Command gen_adr_index regenerates the ADR index table in docs/adr/README.md.
//
// It is the single source of truth for the index: each row is derived from an ADR's title
// heading (`# ADR-NNNN — Title`) and its `Status:` paragraph, so the index can never drift from
// the ADRs themselves. Run it via `make adr-index`; CI runs it and fails if the committed index
// is out of date.
//
// Usage:
//
//	go run scripts/gen_adr_index.go
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const (
	adrDir     = "docs/adr"
	indexFile  = "docs/adr/README.md"
	beginMark  = "<!-- BEGIN GENERATED ADR INDEX -->"
	endMark    = "<!-- END GENERATED ADR INDEX -->"
	genComment = "<!-- Generated by `make adr-index` from each ADR's title heading + Status line. Do not edit by hand. -->"
)

// adrFile matches adr-NNNN-*.md (four-digit number); adr-template.md is deliberately excluded.
var adrFile = regexp.MustCompile(`^adr-(\d{4})-.*\.md$`)

type adr struct {
	num    string // e.g. "0057"
	file   string // basename, used as the link target
	title  string
	status string
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen_adr_index:", err)
		os.Exit(1)
	}
}

func run() error {
	entries, err := os.ReadDir(adrDir)
	if err != nil {
		return err
	}

	var adrs []adr
	for _, e := range entries {
		m := adrFile.FindStringSubmatch(e.Name())
		if m == nil {
			continue
		}
		a, err := parseADR(filepath.Join(adrDir, e.Name()))
		if err != nil {
			return fmt.Errorf("%s: %w", e.Name(), err)
		}
		a.num, a.file = m[1], e.Name()
		adrs = append(adrs, a)
	}
	sort.Slice(adrs, func(i, j int) bool { return adrs[i].num < adrs[j].num })

	var b strings.Builder
	b.WriteString(beginMark + "\n")
	b.WriteString(genComment + "\n")
	b.WriteString("| # | Title | Status |\n")
	b.WriteString("|---|-------|--------|\n")
	for _, a := range adrs {
		fmt.Fprintf(&b, "| [%s](%s) | %s | %s |\n", a.num, a.file, cell(a.title), cell(a.status))
	}
	b.WriteString(endMark)

	return spliceIndex(b.String())
}

// parseADR extracts the title from the first `# ADR-NNNN — Title` heading and the full `Status:`
// paragraph (continuation lines joined until the first blank line).
func parseADR(path string) (adr, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return adr{}, err
	}
	lines := strings.Split(string(data), "\n")

	var a adr
	for _, ln := range lines {
		if strings.HasPrefix(ln, "# ") {
			// "# ADR-0057 — Title" → title after the em-dash separator.
			if _, title, ok := strings.Cut(ln, " — "); ok {
				a.title = strings.TrimSpace(title)
			}
			break
		}
	}
	if a.title == "" {
		return adr{}, fmt.Errorf("no `# ADR-NNNN — Title` heading found")
	}

	for i, ln := range lines {
		if !strings.HasPrefix(ln, "Status:") {
			continue
		}
		para := []string{strings.TrimSpace(strings.TrimPrefix(ln, "Status:"))}
		for _, cont := range lines[i+1:] {
			if strings.TrimSpace(cont) == "" {
				break
			}
			para = append(para, strings.TrimSpace(cont))
		}
		a.status = strings.Join(para, " ")
		break
	}
	if a.status == "" {
		return adr{}, fmt.Errorf("no `Status:` line found")
	}
	return a, nil
}

// cell makes text safe for a Markdown table cell: escape pipes and collapse whitespace.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.Join(strings.Fields(s), " ")
}

// spliceIndex replaces the region between the BEGIN/END markers in indexFile with block.
func spliceIndex(block string) error {
	data, err := os.ReadFile(indexFile)
	if err != nil {
		return err
	}
	content := string(data)

	start := strings.Index(content, beginMark)
	end := strings.Index(content, endMark)
	if start < 0 || end < 0 || end < start {
		return fmt.Errorf("%s: missing or malformed BEGIN/END ADR index markers", indexFile)
	}
	end += len(endMark)

	updated := content[:start] + block + content[end:]
	if updated == content {
		return nil
	}
	return os.WriteFile(indexFile, []byte(updated), 0o644)
}
